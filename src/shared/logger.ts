type DiagnosticCode =
  | 'CLOSE_GUARD_FAILED'
  | 'AUDIO_CONTEXT_CLOSE_FAILED'
  | 'CALIBRATION_CLEANUP_FAILED'
  | 'PRACTICE_CLEANUP_FAILED'
  | 'STORAGE_CANCEL_FAILED'
  | 'BACKUP_LISTENER_REMOVE_FAILED'
  | 'RECORDING_SCORE_UNAVAILABLE'
  | 'RECORDING_LISTENER_REMOVE_FAILED'
  | 'RECORDING_LISTENER_FAILED'
  | 'AI_SETUP_LISTENER_FAILED'
  | 'AI_SETUP_LISTENER_REMOVE_FAILED'
  | 'BACKING_LISTENER_FAILED'
  | 'BACKING_LISTENER_REMOVE_FAILED'
  | 'YOUTUBE_SESSION_CLOSE_FAILED'
  | 'SCORE_WARNING'
  | 'SCORE_IMPORT_FAILED'
  | 'APP_RENDER_FAILED'
  | 'UNCAUGHT_ERROR'
  | 'UNHANDLED_REJECTION';

// 사용자 경로나 오류 원문을 수집하지 않고 고정된 진단 코드만 기록합니다.
export function logDiagnostic(
  level: 'error' | 'warn',
  code: DiagnosticCode,
): void {
  console[level]('[GuitarLab]', code);
}
